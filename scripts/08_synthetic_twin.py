"""08 - Fit the synthetic twin to the real analysis panel and release a public
synthetic panel.

The twin is the call's and the OS transparency policy's named alternative
when licensed microdata cannot be shared. It preserves the panel's structure
(coverage patterns, sector composition conditional on exposure), the
dependence among firm-level treatments and moderators (Gaussian copula), and
the within/between/serial structure of outcomes and controls. No real row is
copied; marginals are evaluated at fresh uniforms.

usage: python3 scripts/08_synthetic_twin.py [plant]   ('plant' adds the full-sample
       real-data H1 and moderator estimates so the public pipeline reproduces
       the direction and approximate size of the published results)
Outputs: synthetic/twin_params.pkl, synthetic/panel_synthetic.parquet,
         synthetic/firms_synthetic.parquet, synthetic/README.md
"""
import sys, pickle, json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import numpy as np, pandas as pd
from nullworld import synth

FIRM_COLS = ["expo_beta_z", "expo_human_z", "expo_lm_z", "expo_nonlang_z", "ilm_share_z", "slack_cash_z",
             "analysts_z", "firm_age_z", "remote_z", "ai_talent_pre_z", "pyramid_z", "entry_wage_z",
             "hhi_ind_z", "rd_int_z", "pre_log_hc", "pre_hire_growth"]
ROW_COLS = ["tilt_exp", "hire_sen_mean", "entry_rate", "log_hc_l1", "hire_rate_l1", "sep_rate_l1", "log_at_l1",
            "roa_l1", "lev_l1", "sales_growth_l1", "rd_at_l1", "hires_all"]


def main():
    (ROOT / "synthetic").mkdir(exist_ok=True)
    panel = pd.read_parquet(ROOT / "data/analysis/panel.parquet")
    firms = pd.read_parquet(ROOT / "data/analysis/firms.parquet")
    params = synth.fit(panel, firms, FIRM_COLS, ROW_COLS)
    (ROOT / "synthetic/twin_params.pkl").write_bytes(pickle.dumps(params))
    eff = None
    if len(sys.argv) > 1 and sys.argv[1] == "plant":
        t = json.loads((ROOT / "tables/09_testbed.json").read_text())
        sdw = params["rowp"]["tilt_exp"]["sd_within"]
        beta = t["h1"][1]["b"] / sdw
        nwc = json.loads((ROOT / "tables/nwc.json").read_text())
        certified = [m.replace("_z", "") for m, v in nwc.get("typeB", {}).items() if v.get("p_holm_package", 1) < 0.05]
        gam = {m["label"] + "_z": m["b"] / sdw for m in t["moderators_single"] if m["label"] in certified}
        eff = {"tilt_exp": {"treatment": "expo_beta_z", "beta": beta, "gammas": gam}}
    p, f = synth.generate(params, seed=20261101, effects=eff, outcome_dir={"tilt_exp": 1, "hire_sen_mean": 1, "entry_rate": -1})
    p["hires_all"] = np.maximum(np.round(np.exp(np.clip(np.log(np.maximum(p.hires_all, 1)), 0, 12))), 10)
    p["S1"] = True; p["S2"] = p.hires_all >= 30
    p["S3"] = p.groupby("firm_idx").year.transform("nunique") >= 8
    p["gvkey"] = p.firm_idx
    for y in range(2017, 2026):
        p[f"c2_size_{y}"] = f.pre_log_hc.to_numpy()[p.firm_idx] * (p.year == y)
        p[f"c2_growth_{y}"] = f.pre_hire_growth.to_numpy()[p.firm_idx] * (p.year == y)
    f["gvkey"] = f.firm_idx
    p.to_parquet(ROOT / "synthetic/panel_synthetic.parquet", index=False)
    f.to_parquet(ROOT / "synthetic/firms_synthetic.parquet", index=False)
    (ROOT / "synthetic/README.md").write_text(
        "# Synthetic twin\n\nGenerated by `scripts/08_synthetic_twin.py` from `nullworld/synth.py`. "
        f"{len(f):,} synthetic firms, {len(p):,} firm-years. No real record is contained; firm identifiers are "
        "arbitrary integers. Use it to run every script from 10 onward (set NULLWORLD_DATA=synthetic).\n"
        + ("Planted effects: " + json.dumps(eff, default=float) if eff else "No planted effects (null twin).") + "\n")
    print(len(f), len(p))


if __name__ == "__main__":
    main()
